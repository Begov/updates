"""Общие флаги запуска дочерних процессов.

Зачем отдельным модулем. Флаг «не показывать консольное окно» жил копией в
`real_photo.py` и применялся ровно в одном месте — в `CodexRunner`. Все
остальные запуски CLI-агентов (адаптация промптов, переписывание после цензуры,
режиссёр Pass 1 и Pass 2, Claude Code) шли без него, и у пользователя на каждом
обращении к режиссёру мигало чёрное окно `codex-x86_64-pc-windows-msvc.exe` —
десятки раз за прогон (жалоба 01.09).

Один источник правды: добавлять флаг в новый вызов теперь нечего забывать —
достаточно распаковать `NO_WINDOW`.

На поведение процесса флаг не влияет: он только прячет окно. Вне Windows —
пустой словарь, распаковка ничего не добавляет.
"""
from __future__ import annotations

import platform

# CREATE_NO_WINDOW: консольный процесс запускается без своего окна.
_CREATE_NO_WINDOW = 0x08000000

NO_WINDOW: dict = (
    {"creationflags": _CREATE_NO_WINDOW}
    if platform.system() == "Windows" else {}
)
