"""Shared Codex credential location and loading helpers."""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, Optional


def codex_home() -> Path:
    """Return the stable user-level Codex home used by every BegoFrame process."""
    configured = (os.environ.get('CODEX_HOME') or '').strip()
    return Path(configured).expanduser() if configured else Path.home() / '.codex'


def codex_env(base_env: Optional[dict] = None) -> dict:
    """Return a process environment pinned to the same Codex home."""
    env = dict(base_env if base_env is not None else os.environ)
    env['CODEX_HOME'] = str(codex_home())
    return env


def auth_file() -> Path:
    return codex_home() / 'auth.json'


def sessions_dir() -> Path:
    return codex_home() / 'sessions'


def _keyring_account(home: Path) -> str:
    """Match the account key generated by the official Codex CLI."""
    try:
        canonical = home.resolve(strict=True)
    except (FileNotFoundError, OSError):
        canonical = home
    digest = hashlib.sha256(str(canonical).encode('utf-8')).hexdigest()
    return f'cli|{digest[:16]}'


def _load_macos_keychain(home: Path) -> Optional[Dict[str, Any]]:
    if sys.platform != 'darwin':
        return None
    try:
        result = subprocess.run(
            [
                '/usr/bin/security',
                'find-generic-password',
                '-s', 'Codex Auth',
                '-a', _keyring_account(home),
                '-w',
            ],
            capture_output=True,
            text=True,
            encoding='utf-8',
            errors='replace',
            timeout=5,
        )
        if result.returncode != 0 or not result.stdout.strip():
            return None
        data = json.loads(result.stdout.strip())
        return data if isinstance(data, dict) else None
    except (OSError, subprocess.SubprocessError, json.JSONDecodeError):
        return None


def _load_json_file(path: Path) -> Optional[Dict[str, Any]]:
    try:
        data = json.loads(path.read_text(encoding='utf-8'))
        return data if isinstance(data, dict) else None
    except (OSError, json.JSONDecodeError):
        return None


def _migrate_legacy_auth(home: Path) -> Optional[Dict[str, Any]]:
    """Recover credentials from early portable builds that used a local home."""
    install_root = Path(__file__).resolve().parents[2]
    destination = home / 'auth.json'
    for legacy in (
        install_root / '.codex' / 'auth.json',
        install_root / 'Codex' / '.codex' / 'auth.json',
    ):
        data = _load_json_file(legacy)
        if not data:
            continue
        try:
            destination.parent.mkdir(parents=True, exist_ok=True)
            temp = destination.with_suffix('.json.tmp')
            shutil.copy2(legacy, temp)
            os.chmod(temp, 0o600)
            temp.replace(destination)
        except OSError:
            pass
        return data
    return None


def load_auth() -> Optional[Dict[str, Any]]:
    """Load Codex credentials from auth.json or the macOS Keychain."""
    home = codex_home()
    return (
        _load_json_file(home / 'auth.json')
        or _load_macos_keychain(home)
        or _migrate_legacy_auth(home)
    )
